"""Contratos de infraestructura utilizados por los casos de uso."""
from typing import Protocol


class EventQueue(Protocol):
    def enqueue(self, event: dict) -> str: ...
    def peek(self) -> tuple | None: ...
    def ack(self, key: str) -> None: ...
    def size(self) -> int: ...
    def healthy(self) -> bool: ...


class Repository(Protocol):
    def create_device(self, values: tuple, token_hash: str) -> dict: ...
    def device(self, device_id: str) -> dict | None: ...
    def devices(self) -> list: ...
    def process(self, event: dict) -> bool: ...
    def alerts(self, limit: int, offset: int) -> list: ...
    def acknowledge(self, alert_id: str) -> bool: ...
    def readings(self, device_id: str, limit: int, offset: int) -> list: ...
    def summary(self) -> dict: ...
